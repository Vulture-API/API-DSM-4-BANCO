import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import test from "node:test";
import pg from "pg";

const url = process.env.TEST_DATABASE_URL;
const migration = readFileSync(new URL("../migrations/021_sensor_calibration.sql", import.meta.url), "utf8");

test("SCRUM-600 guarda ganho e offset por sensor, offset no tipo e recusa fator ou ganho zero", { skip: !url }, async () => {
  const schema = `it_calibration_${randomUUID().replaceAll("-", "")}`;
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    await client.query(`CREATE SCHEMA ${schema}; SET search_path TO ${schema}`);
    await client.query(`
      CREATE TABLE sensor_types (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(50) UNIQUE NOT NULL,
        factor decimal(10,2) NULL,
        gain decimal(10,2) NULL
      );
      CREATE TABLE sensors (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sensor_type_id integer NOT NULL REFERENCES sensor_types (id),
        local_identifier varchar(50) NOT NULL
      );
      INSERT INTO sensor_types (name, factor, gain) VALUES
        ('Sem calibração', NULL, NULL), ('Zeros antigos', 0, 0), ('Vento', 3.6, 1.5);
      INSERT INTO sensors (sensor_type_id, local_identifier) VALUES (1, 'temp');
    `);
    await client.query(migration);

    const type = async (name) => (await client.query(
      "SELECT factor::text, gain::text, offset_value::text FROM sensor_types WHERE name = $1", [name],
    )).rows[0];
    assert.deepEqual(await type("Sem calibração"), { factor: null, gain: null, offset_value: null });
    assert.deepEqual(await type("Zeros antigos"), { factor: null, gain: null, offset_value: null });
    assert.deepEqual(await type("Vento"), { factor: "3.60", gain: "1.50", offset_value: null });

    const sensor = async () => (await client.query(
      "SELECT gain::text, offset_value::text, model FROM sensors WHERE id = 1",
    )).rows[0];
    assert.deepEqual(await sensor(), { gain: null, offset_value: null, model: null });

    // Mais de duas casas: 3,3 V / 4095 passos do ADC do ESP32.
    await client.query("UPDATE sensor_types SET gain = 0.000805860805, offset_value = -12.5 WHERE name = 'Vento'");
    await client.query("UPDATE sensors SET gain = 0.0008, offset_value = -0.125, model = 'LDR GL5528' WHERE id = 1");
    assert.deepEqual(await type("Vento"), { factor: "3.60", gain: "0.000805860805", offset_value: "-12.5" });
    assert.deepEqual(await sensor(), { gain: "0.0008", offset_value: "-0.125", model: "LDR GL5528" });

    for (const [column, value] of [["factor", 0], ["gain", 0], ["gain", "NaN"], ["factor", "Infinity"], ["offset_value", "NaN"], ["offset_value", "-Infinity"]]) {
      await assert.rejects(
        client.query(`UPDATE sensor_types SET ${column} = $1 WHERE name = 'Vento'`, [value]),
        /sensor_types_calibration_valid/,
      );
    }
    for (const [column, value] of [["gain", 0], ["gain", "Infinity"], ["offset_value", "NaN"]]) {
      await assert.rejects(
        client.query(`UPDATE sensors SET ${column} = $1 WHERE id = 1`, [value]),
        /sensors_calibration_valid/,
      );
    }
    await client.query("UPDATE sensors SET offset_value = 0 WHERE id = 1");

    await client.query(migration);
    assert.deepEqual(await type("Vento"), { factor: "3.60", gain: "0.000805860805", offset_value: "-12.5" });
    assert.deepEqual(await sensor(), { gain: "0.0008", offset_value: "0", model: "LDR GL5528" });
  } finally {
    await client.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
    await client.end();
  }
});
