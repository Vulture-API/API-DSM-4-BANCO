import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import test from "node:test";
import pg from "pg";

const url = process.env.TEST_DATABASE_URL;
const migration = readFileSync(new URL("../migrations/016_sensor_limits_and_reading_precision.sql", import.meta.url), "utf8");

async function fixture(partitioned, run) {
  const schema = `it_precision_${randomUUID().replaceAll("-", "")}`;
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    await client.query(`CREATE SCHEMA ${schema}; SET search_path TO ${schema}`);
    await client.query(`
      CREATE TABLE sensors (id integer PRIMARY KEY);
      INSERT INTO sensors VALUES (1);
      CREATE TABLE readings (
        id bigint GENERATED BY DEFAULT AS IDENTITY,
        sensor_id integer NOT NULL REFERENCES sensors(id),
        value decimal(10,2) NOT NULL, unix_time bigint NOT NULL,
        data_consistent boolean NOT NULL DEFAULT true,
        created_at timestamp NOT NULL DEFAULT current_timestamp,
        PRIMARY KEY (${partitioned ? "id, unix_time" : "id"})
      ) ${partitioned ? "PARTITION BY RANGE (unix_time)" : ""};
      ${partitioned ? "CREATE TABLE readings_early PARTITION OF readings FOR VALUES FROM (0) TO (2000000000); CREATE TABLE readings_default PARTITION OF readings DEFAULT;" : ""}
      CREATE INDEX idx_precision_sensor_time ON readings(sensor_id, unix_time DESC);
      INSERT INTO readings(sensor_id,value,unix_time) VALUES (1,12.34,1760000000);
    `);
    await run(client, schema);
  } finally {
    await client.query("ROLLBACK");
    await client.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
    await client.end();
  }
}

for (const partitioned of [false, true]) {
  test(`SCRUM-448 migration repeatable, exact, preserves ${partitioned ? "partitioned" : "ordinary"} readings and MV`, { skip: !url }, async () => {
    const suffix = randomUUID().replaceAll("-", "");
    const owner = `precision_owner_${suffix}`;
    const reader = `precision_reader_${suffix}`;
    await fixture(partitioned, async (client, schema) => {
      try {
        await client.query(`CREATE ROLE ${owner} NOLOGIN; CREATE ROLE ${reader} NOLOGIN; GRANT USAGE, CREATE ON SCHEMA ${schema} TO ${owner}; GRANT USAGE ON SCHEMA ${schema} TO ${reader}; GRANT SELECT ON readings TO ${owner}`);
        await client.query(`
          CREATE MATERIALIZED VIEW mv_latest_readings AS SELECT DISTINCT ON (sensor_id) sensor_id, id AS reading_id, value, unix_time, data_consistent, created_at FROM readings ORDER BY sensor_id, unix_time DESC;
          CREATE UNIQUE INDEX mv_latest_readings_sensor_idx ON mv_latest_readings(sensor_id);
          CREATE INDEX precision_mv_extra ON mv_latest_readings(unix_time);
          COMMENT ON MATERIALIZED VIEW mv_latest_readings IS 'Preserve telemetry MV';
          COMMENT ON COLUMN mv_latest_readings.value IS 'Exact measurement';
          ALTER MATERIALIZED VIEW mv_latest_readings OWNER TO ${owner};
          GRANT SELECT ON mv_latest_readings TO ${reader} WITH GRANT OPTION;
          GRANT SELECT(value) ON mv_latest_readings TO PUBLIC;
          ALTER DEFAULT PRIVILEGES IN SCHEMA ${schema} GRANT SELECT ON TABLES TO PUBLIC;
        `);
        const definition = (await client.query("SELECT pg_get_viewdef('mv_latest_readings'::regclass) AS definition")).rows[0].definition;
        await client.query(migration);
        await client.query(migration);
        assert.equal((await client.query("SELECT value::text AS value FROM readings")).rows[0].value, "12.34");
        await client.query("INSERT INTO readings(sensor_id,value,unix_time) VALUES (1,$1,1760000001)", ["1234567890.12345678901234567890123456789"]);
        assert.equal((await client.query("SELECT value::text AS value FROM readings ORDER BY unix_time DESC LIMIT 1")).rows[0].value, "1234567890.12345678901234567890123456789");
        assert.equal((await client.query("SELECT atttypmod FROM pg_attribute WHERE attrelid='readings'::regclass AND attname='value'")).rows[0].atttypmod, -1);
        assert.equal((await client.query("SELECT pg_get_viewdef('mv_latest_readings'::regclass) AS definition")).rows[0].definition, definition);
        assert.equal((await client.query("SELECT pg_get_userbyid(relowner) AS owner FROM pg_class WHERE oid='mv_latest_readings'::regclass")).rows[0].owner, owner);
        assert.equal((await client.query("SELECT obj_description('mv_latest_readings'::regclass) AS comment")).rows[0].comment, "Preserve telemetry MV");
        assert.equal((await client.query("SELECT col_description('mv_latest_readings'::regclass,3) AS comment")).rows[0].comment, "Exact measurement");
        const acl = await client.query("SELECT grantee::regrole::text AS role, privilege_type, is_grantable FROM pg_class c, LATERAL aclexplode(c.relacl) WHERE c.oid='mv_latest_readings'::regclass");
        assert(acl.rows.some(row => row.role === reader && row.privilege_type === "SELECT" && row.is_grantable));
        assert(!acl.rows.some(row => row.role === "-" || row.role === "public"));
        assert.equal((await client.query("SELECT EXISTS(SELECT 1 FROM pg_attribute a, LATERAL aclexplode(a.attacl) p WHERE a.attrelid='mv_latest_readings'::regclass AND a.attname='value' AND p.grantee=0 AND p.privilege_type='SELECT') AS allowed")).rows[0].allowed, true);
        assert.equal((await client.query("SELECT count(*)::int AS n FROM pg_index WHERE indrelid='mv_latest_readings'::regclass")).rows[0].n, 2);
        await client.query("REFRESH MATERIALIZED VIEW CONCURRENTLY mv_latest_readings");
        assert.equal((await client.query("SELECT value::text AS value FROM mv_latest_readings")).rows[0].value, "1234567890.12345678901234567890123456789");
        await assert.rejects(client.query("INSERT INTO readings(sensor_id,value,unix_time) VALUES(999,1,1)"), { code: "23503" });
        await client.query("UPDATE sensors SET min_value=-0.1234567890123456789, max_value=0.1234567890123456789");
        const limits = (await client.query("SELECT min_value::text, max_value::text FROM sensors")).rows[0];
        assert.equal(limits.min_value, "-0.1234567890123456789");
        for (const [min,max] of [["2","1"],["NaN",null],[null,"Infinity"],["-Infinity",null]]) {
          await assert.rejects(client.query("UPDATE sensors SET min_value=$1,max_value=$2",[min,max]), { code: "23514" });
        }
        await client.query("UPDATE sensors SET min_value=NULL,max_value=NULL");
      } finally {
        // Remove owned objects/grants before dropping these test-only roles.
        await client.query(`ROLLBACK; DROP SCHEMA IF EXISTS ${schema} CASCADE; DROP ROLE IF EXISTS ${reader}; DROP ROLE IF EXISTS ${owner}`);
      }
    });
  });
}

test("SCRUM-448 unknown dependency aborts without partial migration", { skip: !url }, async () => {
  await fixture(false, async client => {
    await client.query("CREATE VIEW external_report AS SELECT value FROM readings");
    await assert.rejects(client.query(migration), /Unknown dependent relation/);
    await client.query("ROLLBACK");
    assert.equal((await client.query("SELECT atttypmod FROM pg_attribute WHERE attrelid='readings'::regclass AND attname='value'")).rows[0].atttypmod, 655366);
    assert.equal((await client.query("SELECT count(*)::int AS n FROM pg_attribute WHERE attrelid='sensors'::regclass AND attname='min_value'")).rows[0].n, 0);
    assert.equal((await client.query("SELECT value::text AS value FROM external_report")).rows[0].value, "12.34");
  });
});

test("SCRUM-448 preserves unpopulated MV and widens manually existing limits", { skip: !url }, async () => {
  await fixture(false, async client => {
    await client.query("ALTER TABLE sensors ADD min_value decimal(10,2), ADD max_value decimal(10,2); UPDATE sensors SET min_value=0,max_value=50; CREATE MATERIALIZED VIEW mv_latest_readings AS SELECT sensor_id,value FROM readings WITH NO DATA; CREATE UNIQUE INDEX mv_latest_readings_sensor_idx ON mv_latest_readings(sensor_id)");
    await client.query(migration);
    assert.equal((await client.query("SELECT relispopulated FROM pg_class WHERE oid='mv_latest_readings'::regclass")).rows[0].relispopulated,false);
    assert.equal((await client.query("SELECT atttypmod FROM pg_attribute WHERE attrelid='sensors'::regclass AND attname='min_value'")).rows[0].atttypmod,-1);
    assert.equal((await client.query("SELECT min_value::text FROM sensors")).rows[0].min_value,"0.00");
  });
});
