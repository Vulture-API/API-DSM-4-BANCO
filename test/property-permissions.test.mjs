import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import test from "node:test";
import pg from "pg";

const url = process.env.TEST_DATABASE_URL;
const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const permissions = read("../migrations/015_role_permissions.sql");
const properties = read("../migrations/019_property_permissions.sql");
const codes = ["properties.create", "properties.delete", "properties.update"];

test("SCRUM-399 concede ao Administrador as permissões de escrita de propriedades", { skip: !url }, async () => {
  const schema = `it_property_permissions_${randomUUID().replaceAll("-", "")}`;
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    await client.query(`CREATE SCHEMA ${schema}; SET search_path TO ${schema}`);
    await client.query(`
      CREATE TABLE roles (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(50) UNIQUE, description varchar(255));
      INSERT INTO roles VALUES (99, 'Administrador', NULL), (42, 'Cliente', NULL);
      CREATE TABLE users (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role_id integer REFERENCES roles(id) ON DELETE RESTRICT, name text);
      CREATE TABLE properties (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text, owner_user_id integer, location text);
      CREATE TABLE sensor_types (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text, unit_of_measure text);
    `);
    await client.query(permissions);
    await client.query(properties);
    const granted = async (role) => (await client.query(
      "SELECT permission_code FROM role_permissions WHERE role_id = $1 AND permission_code LIKE 'properties.%' ORDER BY 1",
      [role],
    )).rows.map((row) => row.permission_code);
    assert.deepEqual(await granted(99), [...codes.slice(0, 2), "properties.read", "properties.update"]);
    assert.deepEqual(await granted(42), []);

    await client.query("DELETE FROM role_permissions WHERE role_id = 99 AND permission_code = 'properties.delete'");
    await client.query(properties);
    assert.deepEqual(await granted(99), ["properties.create", "properties.read", "properties.update"]);
  } finally {
    await client.query("ROLLBACK");
    await client.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
    await client.end();
  }
});
