import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import test from "node:test";
import pg from "pg";

const url = process.env.TEST_DATABASE_URL;
const migration = readFileSync(new URL("../migrations/024_sensor_type_limits.sql", import.meta.url), "utf8");

test("SCRUM-630 guarda limites físicos por tipo, preenche pela unidade e recusa mínimo acima do máximo", { skip: !url }, async () => {
  const schema = `it_type_limits_${randomUUID().replaceAll("-", "")}`;
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    await client.query(`CREATE SCHEMA ${schema}; SET search_path TO ${schema}`);
    await client.query(`
      CREATE TABLE sensor_types (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(50) UNIQUE NOT NULL,
        unit_of_measure varchar(20) NOT NULL
      );
      INSERT INTO sensor_types (name, unit_of_measure) VALUES
        ('Temperatura', '°C'), ('Umidade', '%'), ('Índice Pluviométrico', 'mm'),
        ('Velocidade do Vento', 'km/h'), ('Pressão', 'hPa'), ('Radiação Solar', 'W/m²'),
        ('Luminosidade', 'V');
    `);
    await client.query(migration);

    const limits = async () => Object.fromEntries((await client.query(
      "SELECT name, min_value::text AS min, max_value::text AS max FROM sensor_types ORDER BY id",
    )).rows.map((r) => [r.name, [r.min, r.max]]));
    assert.deepEqual(await limits(), {
      Temperatura: [null, null],
      Umidade: ["0", "100"],
      "Índice Pluviométrico": ["0", null],
      "Velocidade do Vento": ["0", null],
      Pressão: ["0", null],
      "Radiação Solar": ["0", null],
      Luminosidade: [null, null],
    });

    await client.query("UPDATE sensor_types SET min_value = -40, max_value = 80.5 WHERE name = 'Temperatura'");
    await client.query("UPDATE sensor_types SET min_value = 10, max_value = 10 WHERE name = 'Luminosidade'");
    await client.query("UPDATE sensor_types SET min_value = NULL, max_value = NULL WHERE name = 'Pressão'");
    for (const [min, max] of [[5, 1], ["NaN", null], [null, "Infinity"], ["-Infinity", 0]]) {
      await assert.rejects(
        client.query("UPDATE sensor_types SET min_value = $1, max_value = $2 WHERE name = 'Umidade'", [min, max]),
        /sensor_types_limits_valid/,
      );
    }

    // Reaplicar não sobrescreve o que o administrador definiu nem devolve o que ele apagou.
    await client.query(migration);
    const depois = await limits();
    assert.deepEqual(depois.Temperatura, ["-40", "80.5"]);
    assert.deepEqual(depois.Luminosidade, ["10", "10"]);
    assert.deepEqual(depois.Umidade, ["0", "100"]);
    assert.deepEqual(depois.Pressão, [null, null]);
    const constraints = (await client.query(
      "SELECT count(*)::int AS n FROM pg_constraint WHERE conrelid = 'sensor_types'::regclass AND conname = 'sensor_types_limits_valid'",
    )).rows[0].n;
    assert.equal(constraints, 1);
  } finally {
    await client.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
    await client.end();
  }
});
