import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import test from "node:test";
import pg from "pg";

const url = process.env.TEST_DATABASE_URL;
const migration = readFileSync(new URL("../migrations/015_role_permissions.sql", import.meta.url), "utf8");
const seed = readFileSync(new URL("../setup/seed-dev.sql", import.meta.url), "utf8");

test("SCRUM-432 migration and seed are repeatable without restoring revoked grants", { skip: !url }, async () => {
  const schema = `it_permissions_${randomUUID().replaceAll("-", "")}`;
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    await client.query(`CREATE SCHEMA ${schema}; SET search_path TO ${schema}`);
    await client.query(`
      CREATE TABLE roles (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(50) UNIQUE, description varchar(255));
      INSERT INTO roles VALUES (99, 'Administrador', NULL), (42, 'Cliente', NULL);
      CREATE TABLE users (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role_id integer REFERENCES roles(id) ON DELETE RESTRICT, name text);
      CREATE TABLE properties (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text, owner_user_id integer, location text);
      CREATE TABLE sensor_types (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text, unit_of_measure text);
    `);
    await client.query(migration);
    const catalog = await client.query("SELECT code FROM permissions ORDER BY code");
    assert.equal(catalog.rowCount, 31);
    assert.equal((await client.query("SELECT * FROM role_permissions WHERE role_id = 99")).rowCount, 31);
    assert.equal((await client.query("SELECT * FROM role_permissions WHERE role_id = 42")).rowCount, 0);
    await client.query("DELETE FROM role_permissions WHERE role_id = 99 AND permission_code = 'users.delete'");
    await client.query(migration);
    await client.query(seed);
    assert.equal((await client.query("SELECT * FROM role_permissions WHERE role_id = 99")).rowCount, 30);
    await assert.rejects(client.query("INSERT INTO role_permissions VALUES (42, 'unknown')"), { code: "23503" });
    await client.query("INSERT INTO role_permissions VALUES (42, 'users.read')");
    await assert.rejects(client.query("INSERT INTO role_permissions VALUES (42, 'users.read')"), { code: "23505" });
    await client.query("INSERT INTO users (role_id, name) VALUES (42, 'Test')");
    await assert.rejects(client.query("DELETE FROM roles WHERE id = 42"));
    await client.query("DELETE FROM users WHERE role_id = 42; DELETE FROM roles WHERE id = 42");
    assert.equal((await client.query("SELECT * FROM role_permissions WHERE role_id = 42")).rowCount, 0);
    await client.query("DELETE FROM properties; DELETE FROM users; DELETE FROM roles WHERE id = 99");
    await client.query(seed);
    const admin = (await client.query("SELECT id FROM roles WHERE name = 'Administrador'")).rows[0];
    assert.equal((await client.query("SELECT * FROM role_permissions WHERE role_id = $1", [admin.id])).rowCount, 31);
    await client.query("DELETE FROM role_permissions WHERE role_id = $1 AND permission_code = 'users.delete'", [admin.id]);
    await client.query(seed);
    assert.equal((await client.query("SELECT * FROM role_permissions WHERE role_id = $1", [admin.id])).rowCount, 30);
  } finally {
    await client.query("ROLLBACK");
    await client.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
    await client.end();
  }
});
