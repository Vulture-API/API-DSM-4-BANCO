import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import test from "node:test";
import pg from "pg";

const url = process.env.TEST_DATABASE_URL;
const migration = readFileSync(new URL("../migrations/020_station_collection_interval.sql", import.meta.url), "utf8");

test("SCRUM-587 guarda a frequência de coleta por estação, com padrão de 60 s e faixa de 10 s a 1 h", { skip: !url }, async () => {
  const schema = `it_collection_${randomUUID().replaceAll("-", "")}`;
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    await client.query(`CREATE SCHEMA ${schema}; SET search_path TO ${schema}`);
    await client.query(`
      CREATE TABLE stations (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, mac_address varchar(50) UNIQUE NOT NULL);
      INSERT INTO stations (mac_address) VALUES ('AA:BB:CC:DD:EE:01');
    `);
    await client.query(migration);

    const interval = async (mac) => (await client.query(
      "SELECT collection_interval_seconds FROM stations WHERE mac_address = $1", [mac],
    )).rows[0].collection_interval_seconds;
    assert.equal(await interval("AA:BB:CC:DD:EE:01"), 60);

    await client.query("UPDATE stations SET collection_interval_seconds = 10 WHERE id = 1");
    await client.query("INSERT INTO stations (mac_address, collection_interval_seconds) VALUES ('AA:BB:CC:DD:EE:02', 3600)");
    for (const invalid of [9, 3601, 0, -60]) {
      await assert.rejects(
        client.query("UPDATE stations SET collection_interval_seconds = $1 WHERE id = 1", [invalid]),
        /stations_collection_interval_range/,
      );
    }

    await client.query(migration);
    assert.equal(await interval("AA:BB:CC:DD:EE:01"), 10);
    assert.equal(await interval("AA:BB:CC:DD:EE:02"), 3600);
  } finally {
    await client.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
    await client.end();
  }
});
