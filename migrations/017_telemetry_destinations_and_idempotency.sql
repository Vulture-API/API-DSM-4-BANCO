-- SCRUM-451 / SCRUM-449. Apply explicitly with writers stopped and backup.
-- Both historical 016 files remain unchanged. No CASCADE or data deduplication.
BEGIN;
SET LOCAL lock_timeout = '10s';

LOCK TABLE readings IN SHARE ROW EXCLUSIVE MODE;
DO $$
DECLARE duplicate record;
BEGIN
  SELECT sensor_id, unix_time, count(*) AS n INTO duplicate
    FROM readings GROUP BY sensor_id, unix_time HAVING count(*) > 1 LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION 'Duplicate historical readings: sensor_id=%, unix_time=%, count=%. Reconcile explicitly before migration 017.',
      duplicate.sensor_id, duplicate.unix_time, duplicate.n;
  END IF;
END;
$$;

-- Contains the partition key; PostgreSQL propagates to existing/new partitions.
CREATE UNIQUE INDEX IF NOT EXISTS uq_readings_sensor_unix_time ON readings(sensor_id, unix_time);

-- No rounding in the occurrence paired with an exact reading. Unknown dependent
-- views abort the transaction naturally; never drop them with CASCADE.
DO $$
BEGIN
  IF (SELECT atttypmod FROM pg_attribute
      WHERE attrelid='occurrences'::regclass AND attname='value') <> -1 THEN
    ALTER TABLE occurrences ALTER COLUMN value TYPE numeric USING value::numeric;
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS telemetry_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id text NOT NULL,
  stream text NOT NULL,
  entry_id text NOT NULL,
  original_fields bytea NOT NULL,
  station_id integer NULL REFERENCES stations(id) ON DELETE SET NULL,
  measurement_unix_time bigint NULL,
  received_at_ms bigint NULL,
  timestamp_source text NULL,
  warnings text[] NOT NULL DEFAULT '{}',
  completed_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT current_timestamp,
  CONSTRAINT telemetry_events_origin_unique UNIQUE(source_id, stream, entry_id)
);

-- Original content lives in telemetry_events and is not parsed as JSONB. That
-- keeps NUL/surrogates, malformed JSON and arbitrary numeric tokens recoverable.
CREATE TABLE IF NOT EXISTS telemetry_quarantine (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES telemetry_events(id) ON DELETE RESTRICT,
  ordinal integer NOT NULL CHECK (ordinal >= 0),
  reasons text[] NOT NULL CHECK (cardinality(reasons) > 0),
  status text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'RESOLVED')),
  created_at timestamptz NOT NULL DEFAULT current_timestamp,
  resolved_at timestamptz NULL,
  CONSTRAINT telemetry_quarantine_state CHECK ((status='OPEN') = (resolved_at IS NULL)),
  CONSTRAINT telemetry_quarantine_field_unique UNIQUE(event_id, ordinal),
  CONSTRAINT telemetry_quarantine_result_unique UNIQUE(id, event_id, ordinal)
);

CREATE TABLE IF NOT EXISTS telemetry_results (
  event_id bigint NOT NULL REFERENCES telemetry_events(id) ON DELETE RESTRICT,
  ordinal integer NOT NULL CHECK (ordinal >= 0),
  destination text NOT NULL CHECK (destination IN ('reading','inconsistent','duplicate','quarantine')),
  -- Snapshot references intentionally survive catalog/reading deletion. Readings
  -- themselves retain their sensor FK; no FK to readings(id), whose PK can be composite.
  sensor_id integer NULL,
  reading_id bigint NULL,
  reading_unix_time bigint NULL,
  min_value numeric NULL,
  max_value numeric NULL,
  reasons text[] NOT NULL DEFAULT '{}',
  quarantine_id bigint NULL,
  PRIMARY KEY(event_id, ordinal),
  FOREIGN KEY(quarantine_id, event_id, ordinal)
    REFERENCES telemetry_quarantine(id, event_id, ordinal) ON DELETE RESTRICT,
  CONSTRAINT telemetry_results_destination CHECK (
    (destination='quarantine' AND quarantine_id IS NOT NULL AND reading_id IS NULL
      AND reading_unix_time IS NULL AND cardinality(reasons)>0)
    OR (destination<>'quarantine' AND quarantine_id IS NULL AND sensor_id IS NOT NULL
      AND reading_id IS NOT NULL AND reading_unix_time IS NOT NULL AND ordinal>0)
  )
);

CREATE INDEX IF NOT EXISTS idx_telemetry_quarantine_open
  ON telemetry_quarantine(created_at, id) WHERE status='OPEN';
CREATE INDEX IF NOT EXISTS idx_telemetry_results_reading
  ON telemetry_results(reading_id, reading_unix_time) WHERE reading_id IS NOT NULL;

COMMIT;
