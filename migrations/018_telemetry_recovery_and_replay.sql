-- SCRUM-530: operational audit, without rewriting original destinations.
BEGIN;
SET LOCAL lock_timeout='10s';
ALTER TABLE telemetry_events ADD COLUMN IF NOT EXISTS legacy_max_id text NULL;

CREATE TABLE IF NOT EXISTS telemetry_replay_requests (
  request_id uuid PRIMARY KEY,
  quarantine_id bigint NOT NULL REFERENCES telemetry_quarantine(id) ON DELETE RESTRICT,
  operator_name text NOT NULL CHECK(length(btrim(operator_name))>0),
  justification text NOT NULL CHECK(length(btrim(justification))>0),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS telemetry_replay_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id uuid NOT NULL REFERENCES telemetry_replay_requests(request_id) ON DELETE RESTRICT,
  processor_version text NOT NULL,
  status text NOT NULL DEFAULT 'RUNNING' CHECK(status IN
    ('RUNNING','SUCCEEDED','PARTIAL','REJECTED','TECHNICAL_FAILURE','INTERRUPTED')),
  error_code text NULL,
  started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  finished_at timestamptz NULL,
  CONSTRAINT telemetry_replay_attempt_state CHECK((status='RUNNING')=(finished_at IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_replay_request_attempt ON telemetry_replay_attempts(request_id,id DESC);
CREATE INDEX IF NOT EXISTS idx_replay_quarantine_request ON telemetry_replay_requests(quarantine_id,created_at);
CREATE TABLE IF NOT EXISTS telemetry_replay_results (
  attempt_id bigint NOT NULL REFERENCES telemetry_replay_attempts(id) ON DELETE RESTRICT,
  event_id bigint NOT NULL REFERENCES telemetry_events(id) ON DELETE RESTRICT,
  ordinal integer NOT NULL CHECK(ordinal>=0),
  destination text NOT NULL CHECK(destination IN ('reading','inconsistent','duplicate','rejected')),
  sensor_id integer NULL,
  reading_id bigint NULL,
  reading_unix_time bigint NULL,
  min_value numeric NULL,
  max_value numeric NULL,
  reasons text[] NOT NULL DEFAULT '{}',
  timestamp_source text NULL,
  legacy_max_id text NULL,
  PRIMARY KEY(attempt_id,ordinal),
  CONSTRAINT telemetry_replay_result_destination CHECK(
    (destination='rejected' AND reading_id IS NULL AND cardinality(reasons)>0)
    OR (destination<>'rejected' AND reading_id IS NOT NULL AND sensor_id IS NOT NULL
      AND reading_unix_time IS NOT NULL AND ordinal>0))
);
-- This records successful fields from an event-wide rejection across attempts.
CREATE UNIQUE INDEX IF NOT EXISTS uq_replay_completed_field ON telemetry_replay_results(event_id,ordinal)
  WHERE destination<>'rejected';
CREATE INDEX IF NOT EXISTS idx_replay_event_field ON telemetry_replay_results(event_id,ordinal);

CREATE TABLE IF NOT EXISTS telemetry_recovery_incidents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id text NOT NULL,
  stream text NOT NULL,
  group_name text NOT NULL,
  entry_id text NOT NULL,
  reason text NOT NULL CHECK(reason='missing_stream_content'),
  durable_event_id bigint NULL REFERENCES telemetry_events(id) ON DELETE RESTRICT,
  first_seen_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  last_seen_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  observations bigint NOT NULL DEFAULT 1,
  UNIQUE(source_id,stream,group_name,entry_id,reason)
);
COMMIT;
