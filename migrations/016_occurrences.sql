-- SCRUM-395 (US09): ocorrências de falhas e inconsistências.
--   SCRUM-423 — estações sem comunicação
--   SCRUM-424 — limites mínimo/máximo configurados nos sensores
--   SCRUM-425 — registro e consulta das ocorrências
--
-- Idempotente e sem movimentação de dados: só acrescenta colunas nulas, uma
-- tabela nova, índices, o checkpoint da rotina e três permissões. Funciona com
-- `readings` comum ou particionada (010): occurrences.reading_id não tem FK,
-- pelo mesmo motivo de triggered_alerts após a 010 (PK composta).
BEGIN;

-- Limites dos sensores (SCRUM-424) -------------------------------------------
-- Nulos = sem limite naquele lado. Mesma precisão de readings.value.
ALTER TABLE sensors ADD COLUMN IF NOT EXISTS min_value decimal(10,2) NULL;
ALTER TABLE sensors ADD COLUMN IF NOT EXISTS max_value decimal(10,2) NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'sensors_limits_check') THEN
    ALTER TABLE sensors ADD CONSTRAINT sensors_limits_check
      CHECK (min_value IS NULL OR max_value IS NULL OR min_value <= max_value);
  END IF;
END;
$$;

-- Ocorrências (SCRUM-425) ----------------------------------------------------
CREATE TABLE IF NOT EXISTS occurrences (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  type varchar(30) NOT NULL,
  status varchar(10) NOT NULL DEFAULT 'OPEN',
  station_id integer NOT NULL,
  sensor_id integer NULL,
  reading_id bigint NULL,
  value decimal(10,2) NULL,
  description varchar(255) NOT NULL,
  detected_at timestamp NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
  resolved_at timestamp NULL,
  CONSTRAINT occurrences_pk PRIMARY KEY (id),
  CONSTRAINT occurrences_type_check
    CHECK (type IN ('COMMUNICATION_FAILURE', 'OUT_OF_RANGE')),
  CONSTRAINT occurrences_status_check CHECK (status IN ('OPEN', 'RESOLVED')),
  CONSTRAINT occurrences_resolved_check
    CHECK ((status = 'OPEN') = (resolved_at IS NULL)),
  -- Falha de comunicação é da estação; fora do limite é de um sensor/leitura.
  CONSTRAINT occurrences_target_check CHECK (
    (type = 'COMMUNICATION_FAILURE' AND sensor_id IS NULL AND reading_id IS NULL)
    OR (type = 'OUT_OF_RANGE' AND sensor_id IS NOT NULL AND reading_id IS NOT NULL)
  ),
  CONSTRAINT occurrences_station_fk FOREIGN KEY (station_id) REFERENCES stations (id) ON DELETE CASCADE,
  CONSTRAINT occurrences_sensor_fk FOREIGN KEY (sensor_id) REFERENCES sensors (id) ON DELETE CASCADE
);

-- No máximo uma ocorrência aberta por estação (comunicação) e por sensor (fora
-- do limite): uma condição que persiste não gera uma linha por ciclo/leitura.
-- Também torna seguro rodar a rotina em mais de uma instância.
CREATE UNIQUE INDEX IF NOT EXISTS uq_occurrences_open_communication
  ON occurrences (station_id)
  WHERE type = 'COMMUNICATION_FAILURE' AND status = 'OPEN';
CREATE UNIQUE INDEX IF NOT EXISTS uq_occurrences_open_out_of_range
  ON occurrences (sensor_id)
  WHERE type = 'OUT_OF_RANGE' AND status = 'OPEN';

-- Listagem do portal (mais recentes primeiro, com ou sem filtro de estação).
CREATE INDEX IF NOT EXISTS idx_occurrences_detected_at
  ON occurrences (detected_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_occurrences_station_detected_at
  ON occurrences (station_id, detected_at DESC);
CREATE INDEX IF NOT EXISTS idx_occurrences_sensor_id
  ON occurrences (sensor_id) WHERE sensor_id IS NOT NULL;

-- Checkpoint próprio: não divide o do motor de regras.
INSERT INTO processing_checkpoints (key, value)
VALUES ('occurrences_last_reading_id', '0')
ON CONFLICT (key) DO NOTHING;

-- Permissões -----------------------------------------------------------------
-- Só a permissão recém-criada é concedida ao Administrador; reaplicar não
-- devolve uma concessão que o time tenha removido.
DO $$
BEGIN
  IF to_regclass('permissions') IS NOT NULL THEN
    WITH inserted AS (
      INSERT INTO permissions (code, description) VALUES
        ('occurrences.read', 'Consultar ocorrências de falhas'),
        ('occurrences.resolve', 'Resolver ocorrências de falhas'),
        ('occurrences.run', 'Executar manualmente a verificação de ocorrências')
      ON CONFLICT (code) DO NOTHING
      RETURNING code
    )
    INSERT INTO role_permissions (role_id, permission_code)
    SELECT r.id, i.code FROM roles r CROSS JOIN inserted i
    WHERE r.name = 'Administrador'
    ON CONFLICT DO NOTHING;
  END IF;
END;
$$;

COMMIT;
